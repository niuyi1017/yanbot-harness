// Standalone meta-package launcher: installation credentials and code-injection variables never enter Runtime.
export function launcherEnvironment(source = process.env) {
  const names = [
    'PATH',
    'Path',
    'SystemRoot',
    'SYSTEMROOT',
    'WINDIR',
    'COMSPEC',
    'PATHEXT',
    'HOME',
    'USERPROFILE',
    'LOCALAPPDATA',
    'APPDATA',
    'TEMP',
    'TMP',
    'TMPDIR',
    'LANG',
    'LC_ALL',
    'XDG_CACHE_HOME',
    'HTTP_PROXY',
    'HTTPS_PROXY',
    'NO_PROXY',
    'http_proxy',
    'https_proxy',
    'no_proxy',
    'NODE_EXTRA_CA_CERTS',
    'SSL_CERT_FILE',
    'YANBOT_HARNESS_STATE_DIR',
    'YANBOT_HARNESS_ADAPTER',
    'YANBOT_HARNESS_ALLOWED_ORIGINS',
    'YANBOT_HARNESS_REFERENCE_SCENARIO',
    'YANBOT_HARNESS_EXTENSIONS_DIR',
    'CODEBUDDY_API_KEY_FILE',
    'CODEBUDDY_INTERNET_ENVIRONMENT',
    'CODEBUDDY_BASE_URL',
    'CODEBUDDY_CODE_PATH',
  ];
  return Object.fromEntries(names.flatMap((name) => (typeof source[name] === 'string' ? [[name, source[name]]] : [])));
}
